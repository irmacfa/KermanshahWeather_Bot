"""PostgreSQL adapter used by the Vercel deployment.

The legacy bot code uses a small sqlite3-like DB-API surface. This module keeps
that surface while storing all Vercel data in Neon PostgreSQL.
"""
from __future__ import annotations

import os
import re
from typing import Any

import psycopg
from psycopg.rows import tuple_row

_SCHEMA = (
    """CREATE TABLE IF NOT EXISTS users (
        user_id BIGINT PRIMARY KEY, username TEXT, first_name TEXT, last_name TEXT,
        first_seen TEXT, last_seen TEXT, interaction_count BIGINT DEFAULT 0
    )""",
    """CREATE TABLE IF NOT EXISTS chats (
        chat_id BIGINT PRIMARY KEY, chat_type TEXT, title TEXT, username TEXT,
        added_by_id BIGINT, added_by_name TEXT, first_seen TEXT, last_seen TEXT,
        status TEXT DEFAULT 'member'
    )""",
    """CREATE TABLE IF NOT EXISTS user_chat (
        user_id BIGINT, chat_id BIGINT, last_seen TEXT,
        interaction_count BIGINT DEFAULT 0, PRIMARY KEY (user_id, chat_id)
    )""",
    """CREATE TABLE IF NOT EXISTS site_views (
        user_id BIGINT, site_name TEXT, view_count BIGINT DEFAULT 0,
        last_seen TEXT, PRIMARY KEY (user_id, site_name)
    )""",
    "CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT)",
    """CREATE TABLE IF NOT EXISTS events (
        event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT, chat_id BIGINT, message_id BIGINT, created_by BIGINT,
        created_at TEXT, active INTEGER DEFAULT 1,
        platform TEXT NOT NULL DEFAULT 'telegram', group_id BIGINT
    )""",
    """CREATE TABLE IF NOT EXISTS event_refresh_queue (
        event_id BIGINT PRIMARY KEY, created_at TEXT
    )""",
    """CREATE TABLE IF NOT EXISTS event_attendance (
        event_id BIGINT, user_id BIGINT, first_name TEXT, last_name TEXT,
        username TEXT, responded_at TEXT, PRIMARY KEY (event_id, user_id)
    )""",
    """CREATE TABLE IF NOT EXISTS user_profiles (
        platform TEXT NOT NULL DEFAULT 'telegram', user_id BIGINT NOT NULL,
        full_name TEXT, updated_at TEXT, PRIMARY KEY (platform, user_id)
    )""",
    """CREATE TABLE IF NOT EXISTS bot_user_state (
        user_id BIGINT PRIMARY KEY, state JSONB NOT NULL DEFAULT '{}'::jsonb,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )""",
    """CREATE TABLE IF NOT EXISTS processed_updates (
        update_id BIGINT PRIMARY KEY, processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )""",
)

def _sql(statement: str) -> str:
    # Project SQL uses '?' only as positional placeholders; SQL literals contain none.
    return statement.replace("?", "%s")

class Cursor:
    def __init__(self, cursor: Any, lastrowid: int | None = None):
        self._cursor = cursor
        self._lastrowid = lastrowid

    @property
    def lastrowid(self):
        return self._lastrowid

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def execute(self, statement: str, params=()):
        sql = _sql(statement)
        wants_id = bool(re.match(r"\s*INSERT\s+INTO\s+events\b", statement, re.I))
        if wants_id and "RETURNING" not in sql.upper():
            sql += " RETURNING event_id"
        cur = self._cursor.execute(sql, params or ())
        lastrowid = None
        if wants_id:
            row = cur.fetchone()
            lastrowid = int(row[0]) if row else None
        return Cursor(cur, lastrowid)

class Connection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement: str, params=()):
        return Cursor(self.raw.execute(_sql(statement), params or ()))

    def cursor(self):
        return Cursor(self.raw.cursor())

    def __enter__(self):
        self.raw.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self.raw.__exit__(exc_type, exc, tb)

    def close(self):
        self.raw.close()

def connect():
    url = os.getenv("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL is required for the Vercel PostgreSQL deployment")
    raw = psycopg.connect(url, row_factory=tuple_row, connect_timeout=10)
    try:
        with raw.transaction():
            for statement in _SCHEMA:
                raw.execute(statement)
    except Exception:
        raw.close()
        raise
    return Connection(raw)

def load_user_state(user_id: int) -> dict:
    with connect() as conn:
        row = conn.execute(
            "SELECT state FROM bot_user_state WHERE user_id = ?", (user_id,)
        ).fetchone()
        return row[0] if row and isinstance(row[0], dict) else {}

def save_user_state(user_id: int, state: dict) -> None:
    import json
    payload = json.dumps(state, ensure_ascii=False)
    with connect() as conn:
        conn.execute(
            """INSERT INTO bot_user_state (user_id, state, updated_at)
               VALUES (?, %s::jsonb, NOW())
               ON CONFLICT(user_id) DO UPDATE
               SET state = EXCLUDED.state, updated_at = NOW()""".replace("%s::jsonb", "?::jsonb"),
            (user_id, payload),
        )

def claim_update(update_id: int) -> bool:
    with connect() as conn:
        cur = conn.execute(
            "INSERT INTO processed_updates (update_id) VALUES (?) ON CONFLICT DO NOTHING",
            (update_id,),
        )
        return cur.rowcount == 1
